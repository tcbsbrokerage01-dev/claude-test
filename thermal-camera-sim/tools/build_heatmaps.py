"""Turn the colored thermal artworks in the source poster into grayscale heat maps.

Only the cat and the butterfly are used: they move through the heat field as warm bodies.
Each crop is mapped back to a 0..1 "heat" value by finding the nearest color on a
reference rainbow-thermal palette. The light-grey poster background becomes transparent
(alpha 0) so the page can render it as cold ambient air in any palette.

Usage:  python3 tools/build_heatmaps.py path/to/poster.webp
Writes: heatmaps.js  (window.HEATMAPS = {name: "data:image/png;base64,..."})
"""
import base64
import io
import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

# Crop boxes (left, top, right, bottom) in the 614x840 source poster.
BOXES = {
    "cat": (70, 34, 206, 226),
    "butterfly": (308, 78, 522, 208),
}
BG = np.array([239, 239, 239])

# Reference palette used for the inverse mapping: (t, (r, g, b)).
REF = [
    (0.00, (0, 0, 0)), (0.06, (16, 8, 60)), (0.12, (40, 20, 120)), (0.20, (40, 40, 200)),
    (0.28, (30, 90, 255)), (0.36, (0, 170, 255)), (0.44, (0, 230, 220)), (0.52, (40, 230, 90)),
    (0.60, (160, 240, 20)), (0.68, (255, 240, 0)), (0.76, (255, 170, 0)), (0.84, (255, 90, 0)),
    (0.90, (240, 20, 20)), (0.95, (255, 60, 200)), (1.00, (255, 255, 255)),
]


def ref_lut(n=256):
    ts = np.array([s[0] for s in REF])
    cols = np.array([s[1] for s in REF], dtype=float)
    t = np.linspace(0, 1, n)
    return t, np.stack([np.interp(t, ts, cols[:, c]) for c in range(3)], axis=1)


def to_heat(rgb):
    t, lut = ref_lut()
    flat = rgb.reshape(-1, 3).astype(float)
    best = np.zeros(len(flat), dtype=int)
    bestd = np.full(len(flat), np.inf)
    for i, c in enumerate(lut):
        d = ((flat - c) ** 2).sum(1)
        m = d < bestd
        bestd[m], best[m] = d[m], i
    return t[best].reshape(rgb.shape[:2])


def background_mask(img):
    """Alpha mask: 0 where the flat poster background touches the crop border."""
    a = np.asarray(img).astype(int)
    near = np.abs(a - BG).sum(2) <= 18
    bg = np.zeros_like(near)
    bg[0, :], bg[-1, :], bg[:, 0], bg[:, -1] = near[0, :], near[-1, :], near[:, 0], near[:, -1]
    while True:  # grow the border-connected background region through "near" pixels
        grown = bg.copy()
        grown[1:, :] |= bg[:-1, :]
        grown[:-1, :] |= bg[1:, :]
        grown[:, 1:] |= bg[:, :-1]
        grown[:, :-1] |= bg[:, 1:]
        grown &= near
        if (grown == bg).all():
            break
        bg = grown
    for _ in range(2):  # eat the anti-aliased rim, which would otherwise read as a hot halo
        grown = bg.copy()
        grown[1:, :] |= bg[:-1, :]
        grown[:-1, :] |= bg[1:, :]
        grown[:, 1:] |= bg[:, :-1]
        grown[:, :-1] |= bg[:, 1:]
        bg = grown
    alpha = np.where(bg, 0, 255).astype(np.uint8)
    return Image.fromarray(alpha).filter(ImageFilter.GaussianBlur(0.8))


def build(src_path):
    src = Image.open(src_path).convert("RGB")
    out = {}
    for name, box in BOXES.items():
        crop = src.crop(box).filter(ImageFilter.GaussianBlur(0.6))
        alpha = background_mask(crop)
        heat = np.where(np.asarray(alpha) > 0, to_heat(np.asarray(crop)), 0)
        size = (crop.width * 2, crop.height * 2)
        g = Image.fromarray((heat * 255).astype(np.uint8), "L").resize(size, Image.LANCZOS)
        la = Image.merge("LA", (g, alpha.resize(size, Image.LANCZOS)))
        buf = io.BytesIO()
        la.save(buf, "PNG", optimize=True)
        out[name] = "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()
    return out


if __name__ == "__main__":
    maps = build(sys.argv[1])
    target = Path(__file__).resolve().parent.parent / "heatmaps.js"
    target.write_text(
        "// Generated by tools/build_heatmaps.py. Grayscale = heat (0..1), alpha = subject mask.\n"
        "window.HEATMAPS = " + json.dumps(maps, indent=1) + ";\n"
    )
    print({k: len(v) // 1024 for k, v in maps.items()}, "KB each (base64)")
